async function run() {
  console.log("⚡ Inserindo Formas Especiais e Variantes Despertadas no Catálogo...");
  const db = new Database(SQLITE_PATH);

  const insertStmt = db.prepare(`
    INSERT INTO entities (
      id, slug, name, original_name, universe, type, gender, franchise,
      description, images_json, base_aether, popularity_rank,
      base_atk, base_def, base_spd, base_hp, created_at
    ) VALUES (
      ?, ?, ?, ?, ?, ?, ?, ?,
      ?, ?, ?, ?,
      ?, ?, ?, ?, CURRENT_TIMESTAMP
    )
  `);

  let added = 0;
  for (const form of SPECIAL_FORMS) {
    const existing = db.prepare("SELECT id FROM entities WHERE slug = ?").get(form.slug);
    if (existing) continue;

    insertStmt.run(
      crypto.randomUUID(),
      form.slug,
      form.name,
      form.originalName || null,
      form.universe,
      form.type,
      form.gender,
      form.franchise,
      form.description,
      JSON.stringify([form.imageUrl]),
      form.baseAether,
      99999,
      form.atk,
      form.def,
      form.spd,
      form.hp
    );
    added++;
  }

  const total = (db.prepare("SELECT count(*) as n FROM entities").get() as any).n;
  console.log(`✅ ${added} novas formas especiais inseridas! Total no catálogo: ${total}`);
  db.close();
}

run().catch(console.error);
